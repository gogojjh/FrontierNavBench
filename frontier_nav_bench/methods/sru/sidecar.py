"""SRU sidecar offering synchronous inference to the benchmark Python environment.

Run separately with onnxruntime installed: the benchmark environment may lack it,
and the ROS node wall/message scheduling does not suit lockstep simulation. This
process receives one frame, infers once and returns velocity without ROS.

Use multiprocessing.connection on loopback; the client generates a random authkey
and passes it through the environment. Dictionary messages are:
- hello -> ok, pid, model_paths and providers.
- reset -> ok, after clearing LSTM, previous action and low-pass state.
- step with depth_m, robot_pos_w, robot_quat_wxyz, linear_vel_b, angular_vel_b
  and target_pos_w -> ok, cmd, arrived, raw_action, vae_ms and policy_ms.
- shutdown -> ok, then exit.
Errors return ok=False and an error string without terminating the process.

Run ``python -m frontier_nav_bench.methods.sru.sidecar`` from the repository; the client
configures PYTHONPATH for the repository and vendored SRU source. Readiness prints
``VNAV_SRU_READY <port>``. Port zero requests an available system-assigned port.
"""

import os
import sys
from dataclasses import asdict
from multiprocessing.connection import Connection, Listener
from typing import Any, Callable, Dict

from frontier_nav_bench import paths, pins
from frontier_nav_bench.methods.sru.core import SIM_PARAMS, SruCore, SruModel

ENV_PORT = "VNAV_SRU_PORT"  # Listener port: allocated 9982/9983 per README; zero requests a
# system-assigned port
ENV_AUTHKEY = "VNAV_SRU_AUTHKEY"  # Hex authkey randomly generated by the client for each process
READY_TAG = "VNAV_SRU_READY"
IDLE_EXIT_S = 900.0  # Idle wall timeout preventing orphan sidecars after a client crash
# Resolve the benchmark repository root independently of the current directory
WS_ROOT = paths.repository_root()
MODEL_DIR = paths.asset_root() / "weights/sru"  # vae_encoder.onnx / nav_policy.onnx
INTRA_OP_THREADS = 4  # onnxruntime CPU threads, matching the LearningModel default


def load_learning_model() -> SruModel:
    """Load upstream ONNX models on CPU without using GPU resources."""
    pins.ensure_sru_importable()
    pins.require_assets(["weights/sru/vae_encoder.onnx", "weights/sru/nav_policy.onnx"])
    from sru_nav_go2.model import LearningModel

    return LearningModel(
        preprocess_model_path=str(MODEL_DIR / "vae_encoder.onnx"),
        policy_model_path=str(MODEL_DIR / "nav_policy.onnx"),
        policy_scale=list(SIM_PARAMS.policy_scale),
        intra_op_num_threads=INTRA_OP_THREADS,
    )


def handle(core: SruCore, model: SruModel, request: Dict[str, Any]) -> Dict[str, Any]:
    op = request.get("op")
    if op == "hello":
        return {
            "ok": True,
            "pid": os.getpid(),
            "model_dir": str(MODEL_DIR),
            "providers": list(getattr(model, "active_policy_providers", [])),
            "params": asdict(SIM_PARAMS),
        }
    if op == "reset":
        core.reset()
        return {"ok": True}
    if op == "step":
        result = core.step(
            request["depth_m"],
            request["robot_pos_w"],
            request["robot_quat_wxyz"],
            request["linear_vel_b"],
            request["angular_vel_b"],
            request["target_pos_w"],
        )
        return {"ok": True, **asdict(result)}
    if op == "shutdown":
        return {"ok": True}
    return {"ok": False, "error": f"未知 op: {op!r}"}


def serve(conn: Connection, model: SruModel, idle_exit_s: float = IDLE_EXIT_S) -> None:
    """Serve one connection until shutdown, peer disconnect or idle timeout."""
    core = SruCore(model)
    while conn.poll(idle_exit_s):
        try:
            request = conn.recv()
        except EOFError:
            return
        try:
            reply = handle(core, model, request)
        except Exception as exc:  # Return step errors to the client, which determines
        # infrastructure-failure classification
            reply = {"ok": False, "error": f"{type(exc).__name__}: {exc}"}
        conn.send(reply)
        if request.get("op") == "shutdown":
            return


def run(model_factory: Callable[[], SruModel] = load_learning_model) -> None:
    """Listen on the environment-configured port and accept one client connection."""
    port = int(os.environ.get(ENV_PORT, "0"))
    authkey = bytes.fromhex(os.environ[ENV_AUTHKEY])
    model = model_factory()
    with Listener(("127.0.0.1", port), authkey=authkey) as listener:
        print(f"{READY_TAG} {listener.address[1]}", flush=True)
        with listener.accept() as conn:
            serve(conn, model)


if __name__ == "__main__":
    run()
    sys.exit(0)
