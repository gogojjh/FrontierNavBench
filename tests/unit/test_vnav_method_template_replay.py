"""Verify image-goal template refactoring against step-by-step golden replay behavior.

golden/method_trace_imggoal.json was generated by vnav_method_trace.py at pre-refactor commit
19bd0fb. Compare actions, debug fields, VLM request summaries and episode summaries.
"""

from __future__ import annotations

import json
from pathlib import Path

import vnav_method_trace as trace

from vnav_benchmark.methods.imggoal_vlm import ImgGoalVlmMethod
from vnav_benchmark.methods.nav_template import NavMethod
from vnav_benchmark.vlm import prompt

GOLDEN = Path(__file__).resolve().parent / "golden" / "method_trace_imggoal.json"


def test_imggoal_replay_identical_to_pre_refactor() -> None:
    want = json.loads(GOLDEN.read_text())
    got = json.loads(json.dumps(trace.run_all(), sort_keys=True))
    assert set(got) == set(want)
    for name in want:
        assert got[name]["actions"] == want[name]["actions"], name
        assert got[name]["requests"] == want[name]["requests"], name
        assert got[name]["summary"] == want[name]["summary"], name


def test_imggoal_uses_template_and_prompt_unchanged() -> None:
    assert issubclass(ImgGoalVlmMethod, NavMethod)
    assert prompt.prompt_fingerprint() == prompt.PROMPT_FINGERPRINT_V1
